    def __init__(self):
        self._targets: Dict[int, Set[int]] = defaultdict(set)
        self._global_targets: Set[int] = set()
        self._enabled: Dict[int, bool] = defaultdict(bool)

    def add_target(self, chat_id: int, user_id: int):
        self._targets[chat_id].add(user_id)
        logger.info(f"Пользователь {user_id} добавлен в blackhat чата {chat_id}")

    def remove_target(self, chat_id: int, user_id: int):
        self._targets[chat_id].discard(user_id)
        logger.info(f"Пользователь {user_id} убран из blackhat чата {chat_id}")

    def add_global_target(self, user_id: int):
        self._global_targets.add(user_id)

    def remove_global_target(self, user_id: int):
        self._global_targets.discard(user_id)

    def is_target(self, user_id: int, chat_id: int) -> bool:
        return user_id in self._global_targets or user_id in self._targets.get(chat_id, set())

    def set_enabled(self, chat_id: int, enabled: bool):
        self._enabled[chat_id] = enabled

    def is_enabled(self, chat_id: int) -> bool:
        return self._enabled.get(chat_id, False)

    def get_targets(self, chat_id: int) -> Set[int]:
        return set(self._targets[chat_id])

    def get_random_insult(self) -> str:
        return random.choice(self.INSULTS)


